test('ask_again_creates_new_held_order_marked_second_request', async () => {
  const env = makeEnv()
  const first = await authorized(env, 1)
  await env.decisions.stop(first.id)
  const again = await env.decisions.askAgain(first.id)
  assert.notEqual(again.id, first.id)
  assert.equal(again.secondRequest, true)
  assert.notEqual(again.orderId, first.orderId)
  env.mock.buyerApprove(again.orderId)
  await env.lifecycle.ensureAuthorized(again.id)
  await env.investigator.settle(again.id)
  const held = env.store.get(again.id)
  assert.ok([STATES.HELD, STATES.HELD_ASKING].includes(held.state))
  assert.ok(held.signals.some((s) => s.kind === 'second_request'))
  // After two stops the family has to trust the seller before a third request is possible.
  await env.decisions.stop(again.id)
  await assert.rejects(env.decisions.askAgain(again.id), /trust/)
  env.decisions.trustPayee(first.payeeKey)
  const third = await env.decisions.askAgain(again.id)
  assert.equal(third.secondRequest, true)
})

test('pause_rules_requires_24h_and_elder_can_cancel', async () => {
  const env = makeEnv()
  env.decisions.requestPause()
  assert.equal(env.store.household().rulesState, 'PAUSE_REQUESTED')
  assert.ok(env.store.activity().some((a) => a.kind === 'pause_requested'), 'family is told at once')
  env.clock.advance(23 * HOUR)
  await env.scheduler.tick()
  const held = await authorized(env, 4)
  assert.equal(held.state, STATES.HELD, 'rules still apply before 24 h')
  env.decisions.cancelPause()
  assert.equal(env.store.household().rulesState, 'RULES_ON')
  env.clock.advance(5 * HOUR)
  await env.scheduler.tick()
  assert.equal(env.store.household().rulesState, 'RULES_ON')
  env.decisions.requestPause()
  env.clock.advance(24 * HOUR)
  await env.scheduler.tick()
  assert.equal(env.store.household().rulesState, 'RULES_OFF')
  const open = await authorized(env, 1, { payeeKey: scenario(2).payeeKey, amountCents: 6500, message: '' })
  assert.equal(open.state, STATES.CAPTURED, 'with the rules off a new seller is captured at once')
})

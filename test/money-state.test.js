test('approve_and_auto_void_race_only_one_wins', async () => {
  for (const order of ['approve_first', 'tick_first']) {
    const env = makeEnv()
    const p = await authorized(env, 4)
    env.clock.set(p.voidAt)
    const approve = () => env.decisions.approve(p.id)
    const tick = () => env.scheduler.tick()
    await Promise.allSettled(order === 'approve_first' ? [approve(), tick()] : [tick(), approve()])
    env.clock.advance(HOUR)
    await env.scheduler.tick()
    const captured = env.mock.operationCount('capture')
    const voided = env.mock.operationCount('void')
    assert.equal(captured + voided, 1, `${order}: exactly one money operation`)
    const final = env.store.get(p.id)
    assert.equal(final.state, captured === 1 ? STATES.CAPTURED : STATES.VOIDED)
    assert.equal(env.mock.peekAuthorization(p.authorizationId).status, captured === 1 ? 'CAPTURED' : 'VOIDED')
    assert.equal(order === 'approve_first' ? captured : voided, 1, 'the call that reached the lock first wins')
  }
})

test('double_click_stop_voids_once', async () => {
  const env = makeEnv()
  const p = await authorized(env, 1)
  const [a, b] = await Promise.all([env.decisions.stop(p.id), env.decisions.stop(p.id)])
  assert.equal(a.state, STATES.VOIDED)
  assert.equal(b.state, STATES.VOIDED)
  assert.equal(env.mock.callCount('void'), 1)
  assert.equal(env.mock.operationCount('void'), 1)
  assert.equal(env.mock.operationCount('capture'), 0)
})

test('undo_within_window_voids_never_captures', async () => {
  const env = makeEnv()
  const p = await authorized(env, 2)
  await env.decisions.approve(p.id)
  env.clock.advance(5 * MIN)
  const undone = await env.decisions.undo(p.id)
  assert.equal(undone.state, STATES.VOIDED)
  env.clock.advance(2 * HOUR)
  await env.scheduler.tick()
  assert.equal(env.mock.operationCount('capture'), 0)
  assert.equal(env.mock.peekAuthorization(p.authorizationId).status, 'VOIDED')
  assert.equal((await env.decisions.undo(p.id)).state, STATES.VOIDED, 'a second undo click changes nothing')
})

test('approve_near_honor_period_shrinks_undo_and_captures_before_72h', async () => {
  const env = makeEnv({ timers: { undoMs: 2 * HOUR } })
  const p = await authorized(env, 4)
  env.clock.set(p.authorizedAt + 69.5 * HOUR)
  const approved = await env.decisions.approve(p.id)
  assert.equal(approved.captureAt, p.authorizedAt + 71 * HOUR, 'capture is pulled back to the 71 h deadline')
  const view = familyView(env.store.get(p.id), { registry: env.registry, now: env.clock.now(), household: env.store.household() })
  assert.equal(view.undoSecondsLeft, 90 * 60, 'the undo window shrinks from 2 h to 1.5 h')
  env.clock.set(p.authorizedAt + 70.9 * HOUR)
  await env.scheduler.tick()
  assert.equal(env.store.get(p.id).state, STATES.APPROVED_PENDING)
  env.clock.set(p.authorizedAt + 71 * HOUR)
  await env.scheduler.tick()
  const done = env.store.get(p.id)
  assert.equal(done.state, STATES.CAPTURED)
  assert.ok(done.capturedAt - p.authorizedAt < 72 * HOUR)
})

test('auto_void_fires_at_70h_not_after_72h', async () => {
  const env = makeEnv()
  const p = await authorized(env, 4)
  env.clock.set(p.authorizedAt + 70 * HOUR - 1000)
  await env.scheduler.tick()
  assert.equal(env.store.get(p.id).state, STATES.HELD)
  env.clock.set(p.authorizedAt + 70 * HOUR)
  await env.scheduler.tick()
  const done = env.store.get(p.id)
  assert.equal(done.state, STATES.VOIDED)
  assert.equal(done.endedBy, 'timeout')
  assert.ok(done.voidedAt - p.authorizedAt < 72 * HOUR)
  assert.equal(env.mock.operationCount('void'), 1)
})

test('capture_5xx_retries_same_request_id_then_reconciles', async () => {
  const env = makeEnv()
  const p = await authorized(env, 2)
  await env.decisions.approve(p.id)
  // The first capture really happens at PayPal but the answer is lost, and the retries fail too.
  env.mock.injectFault({ op: 'capture', mode: '5xx_after_commit', times: 1 })
  env.mock.injectFault({ op: 'capture', mode: '5xx', times: 5 })
  env.clock.advance(16 * MIN)
  await env.scheduler.tick()
  const captures = env.mock.log.filter((l) => l.op === 'capture')
  assert.equal(captures.length, 3, 'three attempts')
  assert.ok(captures.every((l) => l.requestId === `${p.id}:capture`), 'same Request-Id every time')
  assert.equal(env.mock.operationCount('capture'), 1, 'PayPal captured once')
  const done = env.store.get(p.id)
  assert.equal(done.state, STATES.CAPTURED, 'reconciled from the PayPal order')
  assert.ok(done.captureId)
})

test('void_succeeds_but_webhook_late_state_stays_voided', async () => {
  const env = makeEnv()
  const p = await authorized(env, 1)
  await env.decisions.stop(p.id)
  assert.equal(env.store.get(p.id).state, STATES.VOIDED)
  // Everything PayPal queued so far arrives late, plus a stale AUTHORIZATION.CREATED copy.
  const stale = { id: 'WH-STALE', event_type: 'PAYMENT.AUTHORIZATION.CREATED', resource: { id: p.authorizationId, supplementary_data: { related_ids: { order_id: p.orderId, authorization_id: p.authorizationId } } } }
  const signed = env.mock.signedDelivery(p.payeeKey, stale)
  await env.mock.flush()
  await env.webhooks.handle({ payeeKey: p.payeeKey, headers: signed.headers, event: stale })
  const after = env.store.get(p.id)
  assert.equal(after.state, STATES.VOIDED)
  assert.equal(after.paypalStatus, 'VOIDED')
  assert.ok(after.webhooks.some((w) => w.type === 'PAYMENT.AUTHORIZATION.VOIDED'))
})

test('duplicate_webhook_event_ignored', async () => {
  const env = makeEnv()
  const p = await authorized(env, 3) // known seller: captured at once
  assert.equal(env.store.get(p.id).state, STATES.CAPTURED)
  const refund = env.mock.sellerRefund(env.store.get(p.id).captureId)
  const event = env.mock.pendingEvents().find((e) => e.event_type === 'PAYMENT.CAPTURE.REFUNDED')
  assert.ok(event && refund)
  const send = () => env.webhooks.handle({ payeeKey: p.payeeKey, headers: env.mock.signedDelivery(p.payeeKey, event).headers, event })
  const first = await send()
  const second = await send()
  assert.equal(first.duplicate, false)
  assert.equal(second.duplicate, true)
  assert.equal(env.store.get(p.id).refunded, true)
  assert.equal(env.store.activity().filter((a) => a.kind === 'refunded').length, 1)
})

